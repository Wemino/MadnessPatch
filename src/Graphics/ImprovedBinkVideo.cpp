static void ReleaseVideoResources()
{
	if (VideoPS) VideoPS->Release();

	VideoPS = nullptr;
	VideoDevice = nullptr;
}

static bool CreateVideoResources(IDirect3DDevice9* Device)
{
	if (VideoDevice != Device)
	{
		ReleaseVideoResources();
		VideoDevice = Device;
	}

	if (!VideoPS)
	{
		if (bShaderFailed)
			return false;

		if (FAILED(Device->CreatePixelShader(VideoPixelShader, &VideoPS)))
		{
			bShaderFailed = true;
			ReleaseVideoResources();
			return false;
		}
	}

	return true;
}

static void DrawVideoQuad(void* RHI, UINT PrimitiveType, UINT NumPrimitives, const void* VertexData, UINT VertexDataStride)
{
	reinterpret_cast<void(__thiscall*)(void*, UINT, UINT, const void*, UINT)>(DrawPrimitiveUP)(RHI, PrimitiveType, NumPrimitives, VertexData, VertexDataStride);
}

static bool GetPlaneDesc(IDirect3DDevice9* Device, DWORD Sampler, D3DSURFACE_DESC& Desc)
{
	IDirect3DBaseTexture9* Texture = nullptr;
	Device->GetTexture(Sampler, &Texture);

	const bool bResult = Texture && Texture->GetType() == D3DRTYPE_TEXTURE && SUCCEEDED(static_cast<IDirect3DTexture9*>(Texture)->GetLevelDesc(0, &Desc));

	if (Texture) Texture->Release();
	return bResult;
}

static bool DrawFilteredVideo(IDirect3DDevice9* Device, void* RHI, UINT PrimitiveType, UINT NumPrimitives, const void* VertexData, UINT VertexDataStride)
{
	// The engine's shader samples Y in s0, Cr in s1, Cb in s2 and alpha in s3, all bilinear and clamped
	D3DSURFACE_DESC LumaDesc, ChromaDesc;
	if (NumPrimitives != 2 || VertexDataStride != sizeof(BinkVertex) || !GetPlaneDesc(Device, 0, LumaDesc) || !GetPlaneDesc(Device, 1, ChromaDesc) ||
		!CreateVideoResources(Device))
	{
		return false;
	}

	D3DVIEWPORT9 Viewport;
	Device->GetViewport(&Viewport);

	// Offset the quad by half a pixel so that pixels line up with texels
	BinkVertex Quad[4];
	std::memcpy(Quad, VertexData, sizeof(Quad));

	for (BinkVertex& Vertex : Quad)
	{
		Vertex.X -= 1.0f / Viewport.Width;
		Vertex.Y += 1.0f / Viewport.Height;
	}

	// Vertices 0 and 3 are opposite corners
	const float QuadSizeX = std::fabs(Quad[3].X - Quad[0].X) * 0.5f * Viewport.Width;
	const float QuadSizeY = std::fabs(Quad[3].Y - Quad[0].Y) * 0.5f * Viewport.Height;

	IDirect3DPixelShader9* PixelShader = nullptr;
	float SavedSizes[2][4];
	BOOL SavedFlags[2];

	Device->GetPixelShader(&PixelShader);
	Device->GetPixelShaderConstantF(PlaneSizesRegister, SavedSizes[0], 2);
	Device->GetPixelShaderConstantB(0, SavedFlags, 2);

	const float PlaneSizes[2][4] =
	{
		{ static_cast<float>(LumaDesc.Width), static_cast<float>(LumaDesc.Height), 1.0f / LumaDesc.Width, 1.0f / LumaDesc.Height },
		{ static_cast<float>(ChromaDesc.Width), static_cast<float>(ChromaDesc.Height), 1.0f / ChromaDesc.Width, 1.0f / ChromaDesc.Height }
	};

	// EASU only when the video is upscaled, it reshapes edges even at 1:1
	const BOOL Flags[2] = { bAlphaPlane, QuadSizeX > LumaDesc.Width + 0.5f || QuadSizeY > LumaDesc.Height + 0.5f };

	Device->SetPixelShader(VideoPS);
	Device->SetPixelShaderConstantF(PlaneSizesRegister, PlaneSizes[0], 2);
	Device->SetPixelShaderConstantB(0, Flags, 2);
	DrawVideoQuad(RHI, PrimitiveType, NumPrimitives, Quad, VertexDataStride);

	Device->SetPixelShader(PixelShader);
	Device->SetPixelShaderConstantF(PlaneSizesRegister, SavedSizes[0], 2);
	Device->SetPixelShaderConstantB(0, SavedFlags, 2);

	if (PixelShader) PixelShader->Release();
	return true;
}

static void __fastcall BinkDraw_Hook(void* RHI, int, UINT PrimitiveType, UINT NumPrimitives, const void* VertexData, UINT VertexDataStride)
{
	// DrawPrimitiveUP at +0x1A0 in the vtable
	DrawPrimitiveUP = (*reinterpret_cast<uintptr_t**>(RHI))[0x1A0 / 4];

	if (RHI != D3D9DynamicRHI || *reinterpret_cast<BOOL*>(reinterpret_cast<uintptr_t>(RHI) + 0x20) || !DrawFilteredVideo(*reinterpret_cast<IDirect3DDevice9**>(reinterpret_cast<uintptr_t>(RHI) + 0x8), RHI, PrimitiveType, NumPrimitives, VertexData, VertexDataStride))
	{
		DrawVideoQuad(RHI, PrimitiveType, NumPrimitives, VertexData, VertexDataStride);
	}
}

// Draw_Bink_textures(FBinkTextureSet*, ...), the texture set's alpha plane (Atexture at +0xF8) picks the shader with alpha
static void OnDrawBinkTextures(safetyhook::Context& ctx)
{
	const uintptr_t TextureSet = *reinterpret_cast<uintptr_t*>(ctx.esp + 0x4);
	bAlphaPlane = *reinterpret_cast<void**>(TextureSet + 0xF8) != nullptr;
}

static void OnUpdateD3DDevice(safetyhook::Context& ctx)
{
	D3D9DynamicRHI = reinterpret_cast<void*>(ctx.esi);

	ReleaseVideoResources();
}

void ApplyImprovedBinkVideo()
{
	if (!ImprovedBinkVideo) return;

	DWORD addr_BinkDrawCall = GetAddress(Addr::BinkDrawCall);

	// Draw_Bink_textures: mov edx, [edx+1A0h] -> mov edx, offset BinkDraw_Hook
	MemoryHelper::WriteMemory<uint8_t>(addr_BinkDrawCall, 0xBA);
	MemoryHelper::WriteMemory<uintptr_t>(addr_BinkDrawCall + 0x1, reinterpret_cast<uintptr_t>(&BinkDraw_Hook));
	MemoryHelper::MakeNOP(addr_BinkDrawCall + 0x5, 1);

	DrawBinkTexturesHook = safetyhook::create_mid(GetAddress(Addr::DrawBinkTextures), OnDrawBinkTextures);
	UpdateD3DDeviceHook = safetyhook::create_mid(GetAddress(Addr::UpdateD3DDeviceBink), OnUpdateD3DDevice);
}
