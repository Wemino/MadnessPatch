static const DWORD TypeTemp = 0, TypeInput = 1, TypeConst = 2, TypeOutput = 6, TypeSampler = 10;
static const DWORD OpDeclaration = 0x1F, OpComment = 0xFFFE, OpEnd = 0xFFFF;

static DWORD RegisterType(DWORD Param)
{
	return ((Param >> 28) & 7) | ((Param >> 8) & 0x18);
}

static DWORD RegisterIndex(DWORD Param)
{
	return Param & 0x7FF;
}

static bool IsDefinition(DWORD Op)
{
	return Op == 0x51 || Op == 0x30 || Op == 0x2F;
}

static bool IsFlowControl(DWORD Op)
{
	return (Op >= 0x19 && Op <= 0x1E) || (Op >= 0x26 && Op <= 0x2D) || Op == 0x60;
}

template <size_t Count, typename ReplaceType>
static void AppendShaderCode(std::vector<DWORD>& Out, const DWORD (&Code)[Count], ReplaceType Replace)
{
	for (size_t i = 0; i < Count;)
	{
		const size_t Length = (Code[i] >> 24) & 0xF;
		Out.push_back(Code[i]);
		for (size_t p = 1; p <= Length; p++) Out.push_back(Replace(Code[i + p]));
		i += 1 + Length;
	}
}

// GroupCode goes right after the read of the scene depth, "texld r0, v0, s0" in both fog shaders of the game
static bool BuildGroupShader(const DWORD* Code, size_t Count, std::vector<DWORD>& Out)
{
	if (Count < 2 || Code[0] != 0xFFFF0300)
		return false;

	size_t Insert = 0;
	size_t End = 0;
	DWORD Register = 0;
	DWORD Coordinate = 0;
	for (size_t i = 1; i < Count;)
	{
		const DWORD Token = Code[i];
		const DWORD Op = Token & 0xFFFF;
		if (Op == OpEnd)
		{
			End = i;
			break;
		}

		if (Op == OpComment)
		{
			i += 1 + ((Token >> 16) & 0x7FFF);
			continue;
		}

		const size_t Length = (Token >> 24) & 0xF;
		const bool bPredicated = (Token & 0x10000000) != 0;
		if (i + Length >= Count || bPredicated)
			return false;

		const DWORD* Params = &Code[i + 1];
		const bool bDeclaration = Op == OpDeclaration;
		const bool bDefinition = IsDefinition(Op);

		// dcl: the register follows the usage. def: the values follow the register
		for (size_t p = bDeclaration ? 1 : 0; p < (bDefinition ? 1 : Length); p++)
		{
			const DWORD Type = RegisterType(Params[p]);
			const DWORD Index = RegisterIndex(Params[p]);
			const bool bRelative = (Params[p] & 0x2000) != 0;
			const bool bTaken = (Type == TypeTemp && Index >= FirstGroupRegister) || (Type == TypeConst && Index >= FirstGroupConstant) || (Type == TypeSampler && (Index == CountSampler || Index == SumSampler || Index == SceneSampler));

			// A second read of the scene would return the depth of the pixel again
			const bool bSecondRead = Insert && !bDeclaration && Type == TypeSampler && Index == 0;
			if (bRelative || bTaken || bSecondRead)
				return false;
		}

		if (!Insert && !bDeclaration && !bDefinition)
		{
			if (IsFlowControl(Op))
				return false;

			// Plain texld from sampler 0 into a temporary register, alpha included
			if (Op == 0x42 && (Token & 0x00FF0000) == 0 && Length == 3 && RegisterType(Params[0]) == TypeTemp && (Params[0] & 0x00080000) && RegisterType(Params[2]) == TypeSampler && RegisterIndex(Params[2]) == 0)
			{
				Register = RegisterIndex(Params[0]);
				Coordinate = Params[1];
				if (RegisterType(Coordinate) == TypeTemp && RegisterIndex(Coordinate) == Register)
					return false;

				Insert = i + 1 + Length;
			}
		}

		i += 1 + Length;
	}

	if (!Insert || !End)
		return false;

	// y repeated in z and w, the input may only have x and y declared
	const DWORD SwizzleY = (Coordinate >> 18) & 3;
	const DWORD CoordinateXY = (Coordinate & ~0x00F00000u) | (SwizzleY << 20) | (SwizzleY << 22);

	Out.clear();
	Out.reserve(Count + std::size(GroupDeclarations) + std::size(GroupCode));
	Out.push_back(Code[0]);
	Out.insert(Out.end(), std::begin(GroupDeclarations), std::end(GroupDeclarations));
	Out.insert(Out.end(), Code + 1, Code + Insert);

	AppendShaderCode(Out, GroupCode, [&](DWORD Param)
	{
		return RegisterType(Param) == TypeTemp && RegisterIndex(Param) == 0 ? Param | Register : RegisterType(Param) == TypeInput ? CoordinateXY : Param;
	});
	Out.insert(Out.end(), Code + Insert, Code + End + 1);
	return true;
}

// The position goes to a temporary register, TileEpilogue moves the tile out of the view where its texel is 0
static bool BuildTileShader(const DWORD* Code, size_t Count, std::vector<DWORD>& Out)
{
	if (Count < 2 || Code[0] != 0xFFFE0300)
		return false;

	const DWORD NoRegister = ~0u;
	std::vector<size_t> PositionWrites;
	size_t First = 0;
	size_t End = 0;
	DWORD Position = NoRegister;
	DWORD Written = 0;
	for (size_t i = 1; i < Count;)
	{
		const DWORD Token = Code[i];
		const DWORD Op = Token & 0xFFFF;
		if (Op == OpEnd)
		{
			End = i;
			break;
		}

		if (Op == OpComment)
		{
			i += 1 + ((Token >> 16) & 0x7FFF);
			continue;
		}

		const size_t Length = (Token >> 24) & 0xF;
		const bool bPredicated = (Token & 0x10000000) != 0;
		if (i + Length >= Count || bPredicated || IsFlowControl(Op))
			return false;

		const DWORD* Params = &Code[i + 1];
		const bool bDeclaration = Op == OpDeclaration;
		const bool bDefinition = IsDefinition(Op);
		for (size_t p = bDeclaration ? 1 : 0; p < (bDefinition ? 1 : Length); p++)
		{
			const DWORD Type = RegisterType(Params[p]);
			const DWORD Index = RegisterIndex(Params[p]);
			const bool bRelative = (Params[p] & 0x2000) != 0;
			const bool bTaken = (Type == TypeTemp && Index >= FirstTileRegister) || (Type == TypeConst && Index >= FirstTileConstant) || (Type == TypeInput && Index != 0) || Type == TypeSampler;
			if (bRelative || bTaken)
				return false;
		}

		if (bDeclaration)
		{
			// dcl_position o#
			if (Length == 2 && RegisterType(Params[1]) == TypeOutput && (Params[0] & 0x000F001F) == 0)
			{
				if (Position != NoRegister)
					return false;

				Position = RegisterIndex(Params[1]);
			}
		}
		else if (!bDefinition)
		{
			if (!First) First = i;
			if (Length && RegisterType(Params[0]) == TypeOutput && RegisterIndex(Params[0]) == Position)
			{
				PositionWrites.push_back(i + 1);
				Written |= (Params[0] >> 16) & 0xF;
			}
		}

		i += 1 + Length;
	}

	if (!First || !End || Written != 0xF)
		return false;

	Out.clear();
	Out.reserve(Count + std::size(TileDeclarations) + std::size(TilePrologue) + std::size(TileEpilogue));
	Out.push_back(Code[0]);
	Out.insert(Out.end(), std::begin(TileDeclarations), std::end(TileDeclarations));
	Out.insert(Out.end(), Code + 1, Code + First);
	Out.insert(Out.end(), std::begin(TilePrologue), std::end(TilePrologue));

	// Position writes go to r29, write mask kept
	const size_t Moved = Out.size() - First;
	Out.insert(Out.end(), Code + First, Code + End);
	for (size_t Write : PositionWrites) Out[Write + Moved] = (Out[Write + Moved] & ~0x70001FFFu) | FirstTileRegister;

	AppendShaderCode(Out, TileEpilogue, [&](DWORD Param) { return RegisterType(Param) == TypeOutput ? Param | Position : Param; });
	Out.push_back(OpEnd);
	return true;
}

