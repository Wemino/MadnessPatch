// Patched the first time the game draws its fog with it
template <typename ShaderType>
static FogShaderPatch<ShaderType>* GetShaderPatch(IDirect3DDevice9* Device, FogShaderPatch<ShaderType> (&Patches)[4], ShaderType* GameShader, bool (*Build)(const DWORD*, size_t, std::vector<DWORD>&))
{
	FogShaderPatch<ShaderType>* Free = nullptr;
	for (FogShaderPatch<ShaderType>& Patch : Patches)
	{
		if (Patch.Game == GameShader)
			return &Patch;

		if (!Patch.Game && !Free) Free = &Patch;
	}

	if (!Free)
		return nullptr;

	// The reference keeps the pointer from being reused by another shader
	Free->Game = GameShader;
	GameShader->AddRef();

	UINT Size = 0;
	if (SUCCEEDED(GameShader->GetFunction(nullptr, &Size)) && Size >= 8 && Size % 4 == 0)
	{
		std::vector<DWORD> Code(Size / 4);
		std::vector<DWORD> Patched;
		if (FAILED(GameShader->GetFunction(Code.data(), &Size)) || !Build(Code.data(), Code.size(), Patched) || FAILED(CreateShader(Device, Patched.data(), &Free->Patched)))
		{
			Free->Patched = nullptr;
		}
	}

	return Free;
}

